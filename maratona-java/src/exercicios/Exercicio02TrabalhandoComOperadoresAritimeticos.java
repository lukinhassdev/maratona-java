package exercicios;

public class Exercicio02TrabalhandoComOperadoresAritimeticos {
    public static void main(String[] args) {
        // <  >  <=  >=  ==  !=
        // < menor que
        // > maior que
        // <= menor ou igual que
        // >= maior ou igual que
        // == igual a
        // != diferente de

        boolean isDezEmaiorQueVinte = 10 > 20;
        boolean isDezEmenorQueVinte = 10 < 20;
        boolean isDezEmenorOuIgualAVinte = 10 <= 20;
        boolean isDezEmaiorOuIgualAvinte = 10 >= 20;
        boolean isDezEIgualAvinte = 10 == 20;
        boolean isDezEdiferenteDeVinte = 10 != 20;
        System.out.println("isDezEmaiorQueVinte :"+ isDezEmaiorQueVinte);
        System.out.println("isDezEmenorQueVinte :"+ isDezEmenorQueVinte);
        System.out.println("isDezEmenorOuIgualAVinte :"+ isDezEmenorOuIgualAVinte);
        System.out.println("isDezEmaiorOuIgualAvinte :"+ isDezEmaiorOuIgualAvinte);
        System.out.println("isDezEIgualAvinte :"+ isDezEIgualAvinte);
        System.out.println("isDezEdiferenteDeVinte :"+ isDezEdiferenteDeVinte);
    }
}
